"""Assemble business-plan.md from the section files (S20). Run from the repository root:

    python -I docs/business-plan/assemble.py

Section text is copied unchanged. Each section's own "### References" list is removed and merged into one list in
author-year order: identical entries appear once, and two different entries with the same author and year stop the
script (give them 2026a and 2026b in their sections). Edit the section files, then run this again.
"""
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
SECTIONS = HERE / "sections"
ORDER = ["E-problem.md", "D", "B-market.md", "E-bank-changes.md", "A-data-and-controls.md", "E-sdg.md",
         "C-business-model.md", "E-next-steps.md"]
ANNEX = "E-problem-sources.md"
REFERENCES = "### References\n"

SUMMARY = "## Summary\n\n*Placeholder: Emma writes the summary.*\n"
D_PLACEHOLDER = ("## The solution\n\n*Placeholder: Simon's section (the solution with screenshots, SPEC §17) is not "
                 "on `main` yet.*\n")


def split(name: str) -> tuple[str, list[str]]:
    """The section's text without its reference list, and the list's entries."""
    text = (SECTIONS / name).read_text(encoding="utf-8")
    if REFERENCES not in text:
        return text.rstrip() + "\n", []
    body, refs = text.split(REFERENCES, 1)
    return body.rstrip() + "\n", [e.strip() for e in refs.split("\n\n") if e.strip()]


def sort_key(entry: str):
    author, _, rest = entry.partition(" (")
    year = rest.split(")", 1)[0].split(",", 1)[0]  # "2026b", "n.d.-a", "2024"
    return author.lower(), not year.startswith("n.d."), year  # "n.d." before dated works, as in APA


def merged(entries: list[str]) -> list[str]:
    by_key: dict[tuple, str] = {}
    for entry in entries:
        key = sort_key(entry)[:3]
        if key in by_key and by_key[key] != entry:
            raise SystemExit(f"Two different entries for {key[0]} ({key[2]}):\n  {by_key[key]}\n  {entry}")
        by_key[key] = entry
    return [by_key[k] for k in sorted(by_key)]


def annex() -> str:
    # One heading level down so the plan keeps a single title; the wording is unchanged
    text = (SECTIONS / ANNEX).read_text(encoding="utf-8")
    text = re.sub(r"^(#+) ", lambda m: "#" + m.group(1) + " ", text, flags=re.MULTILINE)
    return text.replace("## Sources for", "## Annex: Sources for", 1).rstrip() + "\n"


parts = ["# Filing Scorecard: business plan\n",
         "<!-- Assembled by docs/business-plan/assemble.py from docs/business-plan/sections/. Do not edit this file:\n"
         "     change the section files and run the script again. -->\n",
         SUMMARY]
entries: list[str] = []
for name in ORDER:
    if name == "D":
        parts.append("<!-- D: placeholder -->\n" + D_PLACEHOLDER)
        continue
    body, refs = split(name)
    parts.append(f"<!-- from sections/{name} -->\n" + body)
    entries += refs
parts.append("## References\n\n" + "\n\n".join(merged(entries)) + "\n")
parts.append(f"<!-- from sections/{ANNEX} -->\n" + annex())

out = HERE / "business-plan.md"
out.write_text("\n".join(parts), encoding="utf-8", newline="\n")
print(f"{out.name}: {len(out.read_text(encoding='utf-8').split())} words, {len(merged(entries))} references")
